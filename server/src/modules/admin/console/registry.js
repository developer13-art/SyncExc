const STATUS_KEYWORDS = [
  ['active', 'active'],
  ['suspended', 'suspended'],
  ['pending', 'pending'],
  ['failed', 'failed'],
  ['rejected', 'rejected'],
  ['cancelled', 'canceled'],
  ['canceled', 'canceled'],
  ['open', 'open'],
  ['resolved', 'resolved'],
  ['paused', 'paused'],
  ['approved', 'approved'],
  ['expired', 'expired'],
  ['inactive', 'inactive'],
  ['processing', 'processing'],
  ['under review', 'under_review'],
  ['completed', 'paid'],
  ['settled', 'paid'],
  ['paid', 'paid'],
];

function derivePreset(sectionId, pageId, definition) {
  if (definition.preset) return definition.preset;
  const resourceEntry = RESOURCE_MAP.get(definition.resource);
  if (!resourceEntry || pageId.includes('details') || pageId.includes('overview')) return null;
  if (pageId.includes('create')) return null;

  if (resourceEntry.statusColumn) {
    const column = resourceEntry.statusColumn.replace(/^a\./, '');
    const label = pageId.replace(/-/g, ' ');
    for (const [keyword, value] of STATUS_KEYWORDS) {
      if (label.includes(keyword)) return { [column]: value };
    }
  }
  return null;
}

export function resolvePage(sectionId, pageId) {
  const definition = PAGE_OVERRIDES[`${sectionId}:${pageId}`] || SECTION_DEFAULT[sectionId];
  if (!definition) return null;

  const preset = derivePreset(sectionId, pageId, definition);
  const resourceEntry = definition.resource ? RESOURCE_MAP.get(definition.resource) : null;
  return {
    sectionId,
    pageId,
    display: definition.display || 'list',
    overview: definition.overview || null,
    analytics: definition.analytics || null,
    system: definition.system || null,
    resource: resourceEntry ? toPublicResource(resourceEntry) : null,
    preset,
  };
}

export default { getResource, listResources, resolvePage };
