const RESOURCE_MAP = new Map(RESOURCES.map((entry) => [entry.key, entry]));

export function getResource(key) {
  return RESOURCE_MAP.get(key) || null;
}

export function listResources() {
  return RESOURCES.map(toPublicResource);
}

export function toPublicResource(entry) {
  return {
    key: entry.key,
    label: entry.label,
    section: entry.section,
    columns: entry.columns.map(({ key, label, kind, currencyKey }) => ({
      key,
      label,
      kind,
      ...(currencyKey ? { currencyKey } : {}),
    })),
    filters: entry.filters.map(({ key, label, options }) => ({ key, label, options: options || null })),
    searchable: entry.search.length > 0,
    statusColumn: entry.statusColumn
      ? entry.statusColumn.replace(/^a\./, '')
      : null,
    defaultSort: entry.defaultSort || entry.dateColumn?.replace(/^a\./, '') || 'id',
    actions: entry.actions.map(({ key, label, method, danger, description, fields, scope }) => ({
      key,
      label,
      method,
      danger: Boolean(danger),
      description,
      scope: scope || 'record',
      fields: fields || [],
    })),
    viewPermission: entry.viewPermission,
    managePermission: entry.managePermission,
  };
}

