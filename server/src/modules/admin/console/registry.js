/**
 * SyncExc Server — Admin console resource registry
 *
 * Every admin page is backed by a descriptor here. Descriptors are the only
 * source of SQL identifiers used by the console query service, so admins can
 * never reach a table that is not explicitly allow-listed.
 *
 * Credential, token and signing-material tables are deliberately absent.
 */

const text = (key, label, extra = {}) => ({ key, label, kind: 'text', ...extra });
const date = (key, label, extra = {}) => ({ key, label, kind: 'date', ...extra });
const status = (key = 'status', label = 'Status') => ({ key, label, kind: 'status' });
const number = (key, label, extra = {}) => ({ key, label, kind: 'number', ...extra });
const money = (key, label, currencyKey = 'currency') => ({
  key,
  label,
  kind: 'currency',
  currencyKey,
});
const bool = (key, label, extra = {}) => ({ key, label, kind: 'boolean', ...extra });

const listFilter = (key, label, column, options) => ({ key, label, column, options });

const reasonFields = (extra = []) => [
  { key: 'reason', label: 'Reason', type: 'textarea', required: true, minLength: 10 },
  ...extra,
];

function resource(definition) {
  return {
    idColumn: 'a.id',
    dateColumn: 'a.created_at',
    statusColumn: null,
    search: [],
    filters: [],
    actions: [],
    summary: [],
    ...definition,
    columns: definition.columns.map((column) => ({
      ...column,
      select: column.select || `a.${column.key}`,
    })),
    viewPermission: definition.viewPermission || `admin.${definition.section}.view`,
    managePermission: definition.managePermission || `admin.${definition.section}.manage`,
  };
}

