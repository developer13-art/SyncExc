const env = import.meta.env;

function requireInProduction(value, name, fallback) {
  if (env.PROD && !value) {
    // In production, missing critical config should fail loudly but not crash the app.
    // A neutral fallback is used so the UI can render a clear configuration error.
    console.error(`[config] Missing required environment variable: ${name}`);
    return fallback ?? '';
  }
  return value ?? fallback ?? '';
}

